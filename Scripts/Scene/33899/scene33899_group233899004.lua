function action_ANY_MONSTER_LIVE_1004001(context, evt)
	local tpl_time = ScriptLib.GetGroupVariableValueByGroup(context, "TPL_TIME", 233899001)
	if tpl_time == nil or tpl_time < 0 then
		ScriptLib.PrintContextLog(context, "@@ LUA_WARNING : active_challenge_by_remainTime")
		return -1
	elseif tpl_time < 1 then
		tpl_time = 0
	end
	if 0 ~= ScriptLib.ActiveChallenge(context, 2, 198, tpl_time, 233899004, 24, 0) then
		ScriptLib.PrintContextLog(context, "@@ LUA_WARNING : active_challenge_by_remainTime")
		return -1
	end

	if 0 ~= ScriptLib.ChangeGroupVariableValue(context, "monster_wave", 1) then
		ScriptLib.PrintContextLog(context, "@@ LUA_WARNING : change_GroupVariable")
		return -1
	end

	return 0
end

